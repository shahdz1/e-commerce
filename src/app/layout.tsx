import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import Navbar from "./_LayaoutPages/Navbar/page";
import { Toaster } from "@/components/ui/toast"
import Sessionprovider from "./_LayaoutPages/SessionProvider/SessionProvider";
import { ReactNode } from "react";
import { getServerSession } from "next-auth";
import { authOptions } from "@/next-auth/authOptions";
import Footer from "./_LayaoutPages/Footer/page";
const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "FreshCart",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: { children: ReactNode }) {
  const session = await getServerSession(authOptions)
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <Sessionprovider mySession={session}>
          <Navbar />
          {children}
          <Footer />
          <Toaster />
        </Sessionprovider>
      </body>
    </html>
  );
}
